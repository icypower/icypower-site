#!/usr/bin/env python3
"""Writes the SEO <head> block of every public page from seo/pages.json.

Each page's managed block sits between <!-- SEO:START --> and <!-- SEO:END -->
and is regenerated from scratch on every run, so edit pages.json, not the HTML.
Run from the repo root: python3 seo/inject_head.py
"""
import json, re, html, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
cfg = json.loads((ROOT / 'seo/pages.json').read_text(encoding='utf-8'))
SITE = cfg['site']
BIZ = cfg['business']

def esc(s): return html.escape(s, quote=True)

def org_graph():
    return {
        "@type": ["LocalBusiness", "EntertainmentBusiness"],
        "@id": SITE + "/#business",
        "name": BIZ['name'],
        "alternateName": BIZ['alternateName'],
        "description": BIZ['description'],
        "url": SITE + "/",
        "logo": SITE + "/assets/img/icy_power_Logo.png",
        "image": SITE + "/assets/img/og/og-home.jpg",
        "telephone": BIZ['telephone'],
        "email": BIZ['email'],
        "priceRange": "₪₪",
        "address": {"@type": "PostalAddress", "addressLocality": BIZ['locality'],
                    "addressRegion": BIZ['region'], "addressCountry": "IL"},
        "areaServed": [{"@type": a['type'], "name": a['name']} for a in BIZ['areaServed']],
        "founder": [{"@type": "Person", "name": n} for n in BIZ['founders']],
        "sameAs": BIZ['sameAs'],
        "contactPoint": {"@type": "ContactPoint", "telephone": BIZ['telephone'],
                         "contactType": "sales", "availableLanguage": ["he", "en"],
                         "areaServed": "IL"},
        "knowsAbout": BIZ['knowsAbout'],
        "makesOffer": [{"@type": "Offer", "itemOffered": {"@id": SITE + p['path'] + "#service"}}
                       for p in cfg['pages'] if p.get('service')],
    }

def page_graph(p):
    url = SITE + p['path']
    g = []
    if p['path'] == '/':
        g.append({"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/",
                  "name": BIZ['name'], "inLanguage": "he-IL",
                  "publisher": {"@id": SITE + "/#business"}})
    # Full business node on every page: crawlers don't resolve @id across pages.
    g.append(org_graph())
    g.append({"@type": p.get('pageType', 'WebPage'), "@id": url + "#webpage", "url": url,
              "name": p['title'], "description": p['description'], "inLanguage": "he-IL",
              "isPartOf": {"@id": SITE + "/#website"},
              "about": {"@id": SITE + "/#business"},
              "primaryImageOfPage": SITE + p['image']})
    if p['path'] != '/':
        g.append({"@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Icy Power", "item": SITE + "/"},
            {"@type": "ListItem", "position": 2, "name": p['crumb'], "item": url}]})
    s = p.get('service')
    if s:
        g.append({"@type": "Service", "@id": url + "#service", "name": s['name'],
                  "serviceType": s['serviceType'], "description": p['description'],
                  "url": url, "image": SITE + p['image'],
                  "provider": {"@id": SITE + "/#business"},
                  "areaServed": [{"@type": a['type'], "name": a['name']} for a in BIZ['areaServed']],
                  "audience": {"@type": "Audience", "audienceType": s['audience']}})
    if p.get('faq'):
        g.append({"@type": "FAQPage", "@id": url + "#faq", "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}}
            for q, a in p['faq']]})
    return {"@context": "https://schema.org", "@graph": g}

def block(p):
    url = SITE + p['path']
    img = SITE + p['image']
    lines = [
        '<!-- SEO:START (generated by seo/inject_head.py from seo/pages.json - edit those, not this) -->',
        f'<title>{esc(p["title"])}</title>',
        f'<meta name="description" content="{esc(p["description"])}" />',
        '<meta name="robots" content="index, follow, max-image-preview:large, max-snippet:-1, max-video-preview:-1" />',
        f'<link rel="canonical" href="{url}" />',
        '<meta name="theme-color" content="#1C6E9C" />',
        '<meta name="geo.region" content="IL" />',
        '<meta property="og:locale" content="he_IL" />',
        '<meta property="og:site_name" content="Icy Power" />',
        f'<meta property="og:type" content="{"website" if p["path"] == "/" else "article"}" />',
        f'<meta property="og:url" content="{url}" />',
        f'<meta property="og:title" content="{esc(p.get("ogTitle", p["title"]))}" />',
        f'<meta property="og:description" content="{esc(p["description"])}" />',
        f'<meta property="og:image" content="{img}" />',
        '<meta property="og:image:width" content="1200" />',
        '<meta property="og:image:height" content="630" />',
        f'<meta property="og:image:alt" content="{esc(p["imageAlt"])}" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        f'<meta name="twitter:title" content="{esc(p.get("ogTitle", p["title"]))}" />',
        f'<meta name="twitter:description" content="{esc(p["description"])}" />',
        f'<meta name="twitter:image" content="{img}" />',
        '<script type="application/ld+json">',
        json.dumps(page_graph(p), ensure_ascii=False, indent=1),
        '</script>',
        '<!-- SEO:END -->',
    ]
    return '\n'.join(lines)

# Tags the managed block owns; stray copies outside it are removed.
OWNED = [r'<title>.*?</title>\s*', r'<meta name="description"[^>]*>\s*',
         r'<meta name="robots"[^>]*>\s*', r'<meta property="og:[^>]*>\s*',
         r'<meta name="twitter:[^>]*>\s*', r'<link rel="canonical"[^>]*>\s*']

for p in cfg['pages']:
    f = ROOT / p['file']
    src = f.read_text(encoding='utf-8')
    src = re.sub(r'<!-- SEO:START.*?<!-- SEO:END -->\n?', '', src, flags=re.S)
    head_end = src.index('</head>')
    head, rest = src[:head_end], src[head_end:]
    for pat in OWNED:
        head = re.sub(pat, '', head, flags=re.S)
    # Insert right after the viewport meta (or charset) so it stays near the top.
    m = re.search(r'<meta name="viewport"[^>]*>\n', head) or re.search(r'<meta charset[^>]*>\n', head)
    head = head[:m.end()] + block(p) + '\n' + head[m.end():]
    f.write_text(head + rest, encoding='utf-8')
    print('updated', p['file'])

# ---- sitemap.xml (lastmod = the file's last git commit date, or today) ----
import subprocess, datetime
def lastmod(path):
    out = subprocess.run(['git', 'log', '-1', '--format=%cs', '--', path], cwd=ROOT,
                         capture_output=True, text=True).stdout.strip()
    return out or datetime.date.today().isoformat()

urls = []
for p in cfg['pages']:
    urls.append(
        f'  <url>\n    <loc>{SITE}{p["path"]}</loc>\n    <lastmod>{lastmod(p["file"])}</lastmod>\n'
        f'    <priority>{p.get("priority", "0.5")}</priority>\n'
        f'    <image:image><image:loc>{SITE}{p["image"]}</image:loc></image:image>\n  </url>')
(ROOT / 'sitemap.xml').write_text(
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
    'xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n'
    + '\n'.join(urls) + '\n</urlset>\n', encoding='utf-8')
print('wrote sitemap.xml')
